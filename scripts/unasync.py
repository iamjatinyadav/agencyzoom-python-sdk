#!/usr/bin/env python3
"""Generate the synchronous client (``_sync/``) from the async one (``_async/``).

The async code is the single source of truth; this script rewrites it
token-by-token (``async def`` -> ``def``, ``await x`` -> ``x``,
``AsyncLeads`` -> ``Leads``, ...). ``_compat.py`` and ``__init__.py`` are
hand-written on both sides and are never touched.

Usage::

    python scripts/unasync.py          # regenerate src/agencyzoom/_sync
    python scripts/unasync.py --check  # exit 1 if _sync is out of date (CI)
"""

from __future__ import annotations

import argparse
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACKAGE = ROOT / "src" / "agencyzoom"
SOURCE = PACKAGE / "_async"
TARGET = PACKAGE / "_sync"
HAND_WRITTEN = {"_compat.py", "__init__.py"}

# Order matters: the specific rules run before the generic `Async*` rename.
RULES: list[tuple[str, str]] = [
    (r"\basync def\b", "def"),
    (r"\basync with\b", "with"),
    (r"\basync for\b", "for"),
    (r"\bawait\s+", ""),
    (r"__aenter__", "__enter__"),
    (r"__aexit__", "__exit__"),
    (r"\.aclose\(", ".close("),
    (r"Awaitable\[Any\]", "Any"),
    (r"\bAwaitable, ", ""),
    (r"\bAsync([A-Z]\w*)", r"\1"),
    (r"\basync\b", "sync"),  # prose in docstrings/comments
]


def header(relative: Path) -> str:
    return (
        f"# Generated by scripts/unasync.py from src/agencyzoom/_async/{relative.as_posix()}.\n"
        "# Do not edit: change the async source and regenerate.\n"
    )


def transform(source: str) -> str:
    for pattern, replacement in RULES:
        source = re.sub(pattern, replacement, source)
    return source


def generate(target: Path) -> list[Path]:
    written: list[Path] = []
    for path in sorted(SOURCE.rglob("*.py")):
        relative = path.relative_to(SOURCE)
        if relative.name in HAND_WRITTEN and relative.parent == Path("."):
            continue
        out = target / relative
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(header(relative) + transform(path.read_text("utf-8")), "utf-8")
        written.append(out)
    files = [str(p) for p in written]
    ruff = [sys.executable, "-m", "ruff"]
    # `yield from` is invalid in the async source, so keep the loop form in sync code too.
    subprocess.run(
        [*ruff, "check", "--fix", "--quiet", "--ignore", "UP028", *files], check=False, cwd=ROOT
    )
    subprocess.run([*ruff, "format", "--quiet", *files], check=False, cwd=ROOT)
    return written


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail if _sync is stale")
    args = parser.parse_args()

    if not args.check:
        written = generate(TARGET)
        print(f"Generated {len(written)} files in {TARGET.relative_to(ROOT)}")
        return 0

    with tempfile.TemporaryDirectory(dir=ROOT) as tmp:
        scratch = Path(tmp) / "_sync"
        shutil.copytree(TARGET, scratch)
        generate(scratch)
        stale = [
            p.relative_to(scratch)
            for p in scratch.rglob("*.py")
            if not (TARGET / p.relative_to(scratch)).exists()
            or (TARGET / p.relative_to(scratch)).read_text("utf-8") != p.read_text("utf-8")
        ]
    if stale:
        print("_sync is out of date; run `python scripts/unasync.py`:", *stale, sep="\n  ")
        return 1
    print("_sync is up to date")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
