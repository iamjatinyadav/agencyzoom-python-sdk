#!/usr/bin/env python3
"""Generate ``src/agencyzoom/models/_generated.py`` from the AgencyZoom OpenAPI spec.

Usage::

    python scripts/fetch_spec.py                 # the spec is not committed; download it first
    python scripts/generate_models.py [openapi/agencyzoom.yaml]

Design rules:

* Every component schema becomes a Pydantic model; ``allOf`` becomes inheritance
  and inline objects become nested models named ``<Parent><Property>``.
* Attributes are snake_case with the original camelCase name as alias.
* Schemas reachable from a *response* are fully optional (the API omits fields
  freely). Request-only schemas keep the spec's ``required`` fields so mistakes
  are caught before a request is sent.
* Annotations use ``typing.List``/``Optional`` rather than ``list[...]``/``X | None``:
  Pydantic evaluates them at runtime, and the SDK supports Python 3.8.
* String enums are typed ``Union[Literal[...], str]``: editors autocomplete the
  documented values while undocumented ones still validate.
"""

from __future__ import annotations

import keyword
import re
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_SPEC = ROOT / "openapi" / "agencyzoom.yaml"
OUTPUT = ROOT / "src" / "agencyzoom" / "models" / "_generated.py"

# Names pydantic's BaseModel already uses; fields must not shadow them.
RESERVED = {
    "construct", "copy", "dict", "fields", "json", "parse_file", "parse_obj", "parse_raw",
    "schema", "schema_json", "update_forward_refs", "validate", "to_api",
}  # fmt: skip

# Inline response schemas in `paths` that deserve a named model.
SYNTHETIC_SCHEMAS = {
    "Pipeline": ("/v1/api/pipelines", "get", ("items",)),
}

HEADER = '''\
# This file is generated by scripts/generate_models.py from AgencyZoom's OpenAPI spec.
# Do not edit it by hand: change the generator or the spec, then regenerate.
"""Typed models for every AgencyZoom API schema."""

from __future__ import annotations

from typing import Any, Dict, List, Literal, Optional, Union

from pydantic import Field

from ._base import AgencyZoomModel, OptBool, OptFloat, OptInt
'''


def ref_name(ref: str) -> str:
    return class_name(ref.rsplit("/", 1)[-1])


def class_name(raw: str) -> str:
    parts = re.split(r"[^0-9A-Za-z]+", raw)
    return "".join(p[:1].upper() + p[1:] for p in parts if p)


def snake(name: str) -> str:
    s = re.sub(r"[^0-9A-Za-z_]+", "_", name)
    s = re.sub(r"([A-Z]+)([A-Z][a-z])", r"\1_\2", s)
    s = re.sub(r"([a-z0-9])([A-Z])", r"\1_\2", s)
    s = s.lower().strip("_") or "field"
    if s[0].isdigit():
        s = f"f_{s}"
    if keyword.iskeyword(s) or s in RESERVED or s.startswith("model_"):
        s = f"{s}_"
    return s


def one_line(text: str | None) -> str:
    if not text:
        return ""
    return " ".join(str(text).split()).replace("\\", "\\\\").replace('"""', "'''")


@dataclass
class Field:
    name: str
    alias: str
    annotation: str
    required: bool
    doc: str


@dataclass
class Model:
    name: str
    bases: list[str]
    doc: str
    fields: list[Field] = field(default_factory=list)
    deps: set[str] = field(default_factory=set)
    is_response: bool = False


class Generator:
    def __init__(self, spec: dict[str, Any]) -> None:
        self.spec = spec
        self.schemas: dict[str, dict[str, Any]] = dict(spec["components"]["schemas"])
        for name, (path, method, item_path) in SYNTHETIC_SCHEMAS.items():
            node = spec["paths"][path][method]["responses"]["200"]["content"]["application/json"][
                "schema"
            ]
            for key in item_path:
                node = node[key]
            self.schemas[name] = node
        self.models: dict[str, Model] = {}
        self.response_schemas = self._reachable_from_responses()

    # ---------------------------------------------------------------- analysis

    def _reachable_from_responses(self) -> set[str]:
        seen: set[str] = set()
        stack: list[Any] = []
        for ops in self.spec["paths"].values():
            for op in ops.values():
                if isinstance(op, dict):
                    stack.extend(op.get("responses", {}).values())
        while stack:
            node = stack.pop()
            if isinstance(node, dict):
                ref = node.get("$ref")
                if isinstance(ref, str) and ref.startswith("#/components/schemas/"):
                    raw = ref.rsplit("/", 1)[-1]
                    if raw not in seen:
                        seen.add(raw)
                        stack.append(self.schemas.get(raw, {}))
                stack.extend(node.values())
            elif isinstance(node, list):
                stack.extend(node)
        return {class_name(n) for n in seen} | set(SYNTHETIC_SCHEMAS)

    def _all_properties(self, schema: dict[str, Any]) -> dict[str, Any]:
        props: dict[str, Any] = {}
        for part in schema.get("allOf", []):
            target = self.schemas[part["$ref"].rsplit("/", 1)[-1]] if "$ref" in part else part
            props.update(self._all_properties(target))
        props.update(schema.get("properties") or {})
        return props

    # ---------------------------------------------------------------- typing

    def annotation(self, schema: dict[str, Any], owner: Model, hint: str) -> str:
        if "$ref" in schema:
            target = ref_name(schema["$ref"])
            owner.deps.add(target)
            return target
        if "allOf" in schema and len(schema["allOf"]) == 1:
            return self.annotation(schema["allOf"][0], owner, hint)

        kind = schema.get("type")
        enum = schema.get("enum")
        if kind == "string" or kind == "varchar":
            if enum:
                values = ", ".join(repr(str(v)) for v in enum)
                return f"Union[Literal[{values}], str]"
            return "str"
        if kind == "integer":
            return "int"
        if kind == "number":
            return "float"
        if kind == "boolean":
            return "bool"
        if kind == "array":
            item = self.annotation(schema.get("items") or {}, owner, f"{hint}Item")
            return f"List[{item}]"
        if schema.get("properties") or "allOf" in schema:
            nested = self.build_model(hint, schema, is_response=owner.is_response)
            owner.deps.add(nested.name)
            return nested.name
        extra = schema.get("additionalProperties")
        if isinstance(extra, dict) and extra:
            return f"Dict[str, {self.annotation(extra, owner, f'{hint}Value')}]"
        if kind == "object":
            return "Dict[str, Any]"
        return "Any"

    @staticmethod
    def optional(annotation: str) -> str:
        lenient = {"int": "OptInt", "float": "OptFloat", "bool": "OptBool"}
        if annotation in lenient:
            return lenient[annotation]
        if annotation == "Any":
            return "Any"
        return f"Optional[{annotation}]"

    # ---------------------------------------------------------------- models

    def build_model(
        self, name: str, schema: dict[str, Any], *, is_response: bool | None = None
    ) -> Model:
        if name in self.models:
            return self.models[name]
        if is_response is None:
            is_response = name in self.response_schemas
        model = Model(
            name=name,
            bases=[],
            doc=one_line(schema.get("description")),
            is_response=is_response,
        )
        self.models[name] = model

        inline_props: dict[str, Any] = dict(schema.get("properties") or {})
        for part in schema.get("allOf", []):
            if "$ref" in part:
                model.bases.append(ref_name(part["$ref"]))
            else:
                inline_props.update(part.get("properties") or {})
        model.deps.update(model.bases)

        required = set() if is_response else set(schema.get("required") or [])
        for part in schema.get("allOf", []):
            if not is_response and "$ref" not in part:
                required |= set(part.get("required") or [])

        # Required fields inherited from a base must be re-declared to become required.
        inherited = self._all_properties(schema) if model.bases else {}
        for prop in sorted(required - inline_props.keys()):
            if prop in inherited:
                inline_props[prop] = inherited[prop]

        used: set[str] = set()
        for alias, prop_schema in inline_props.items():
            prop_schema = prop_schema or {}
            py_name = snake(alias)
            while py_name in used:
                py_name = f"{py_name}_"
            used.add(py_name)
            ann = self.annotation(prop_schema, model, f"{name}{class_name(alias)}")
            is_required = alias in required
            doc = one_line(prop_schema.get("description"))
            if "example" in prop_schema and not isinstance(prop_schema["example"], (dict, list)):
                doc = f"{doc} Example: ``{prop_schema['example']}``.".strip()
            model.fields.append(
                Field(
                    name=py_name,
                    alias=alias,
                    annotation=ann if is_required else self.optional(ann),
                    required=is_required,
                    doc=doc,
                )
            )
        return model

    def generate(self) -> str:
        for raw, schema in self.schemas.items():
            self.build_model(class_name(raw), schema or {})

        ordered: list[Model] = []
        state: dict[str, int] = {}

        def visit(model: Model) -> None:
            if state.get(model.name) == 2:
                return
            if state.get(model.name) == 1:  # dependency cycle: forward refs handle it
                return
            state[model.name] = 1
            # Bases must be defined first; nested models are emitted first for readability.
            for dep in sorted(model.deps):
                if dep in self.models:
                    visit(self.models[dep])
            state[model.name] = 2
            ordered.append(model)

        for model in self.models.values():
            visit(model)

        out = [HEADER]
        out.append(
            "__all__ = [\n"
            + "".join(f'    "{m.name}",\n' for m in sorted(ordered, key=lambda m: m.name))
            + "]\n"
        )
        for model in ordered:
            out.append(self.render(model))
        return "\n".join(out)

    @staticmethod
    def render(model: Model) -> str:
        bases = ", ".join(model.bases) or "AgencyZoomModel"
        lines = [f"\nclass {model.name}({bases}):"]
        if model.doc:
            lines.append(f'    """{model.doc}"""')
            if model.fields:
                lines.append("")
        for f in model.fields:
            args: list[str] = []
            if f.alias != f.name:
                args.append(f'alias="{f.alias}"')
            if args or not f.required:
                default = "" if f.required else "None"
                if args:
                    from_field = ", ".join(([f"default={default}"] if default else []) + args)
                    value = f" = Field({from_field})"
                else:
                    value = f" = {default}"
            else:
                value = ""
            lines.append(f"    {f.name}: {f.annotation}{value}")
            if f.doc:
                lines.append(f'    """{f.doc}"""')
        if not model.fields and not model.doc:
            lines.append("    pass")
        return "\n".join(lines) + "\n"


def main() -> None:
    spec_path = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_SPEC
    if not spec_path.exists():
        sys.exit(
            f"{spec_path} not found. The spec isn't stored in this repo (it's AgencyZoom's "
            "proprietary file); download it first with:  make spec"
        )
    spec = yaml.safe_load(spec_path.read_text(encoding="utf-8"))
    source = Generator(spec).generate()
    OUTPUT.write_text(source, encoding="utf-8")
    subprocess.run([sys.executable, "-m", "ruff", "format", "--quiet", str(OUTPUT)], check=False)
    subprocess.run(
        [sys.executable, "-m", "ruff", "check", "--fix", "--quiet", str(OUTPUT)], check=False
    )
    print(f"Wrote {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
